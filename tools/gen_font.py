def parse_bdf(path):
    t = Path(path).read_text(encoding="latin-1")
    ascent = int(re.search(r"FONT_ASCENT (-?\d+)", t).group(1))
    descent = int(re.search(r"FONT_DESCENT (-?\d+)", t).group(1))
    glyphs = {}
    for m in re.finditer(r"ENCODING (-?\d+)\n(.*?)ENDCHAR", t, re.S):
        cp, body = int(m.group(1)), m.group(2)
        dw = int(re.search(r"DWIDTH (-?\d+)", body).group(1))
        w, h, xo, yo = map(int, re.search(r"BBX (-?\d+) (-?\d+) (-?\d+) (-?\d+)", body).group(1, 2, 3, 4))
        rows = re.search(r"BITMAP\n(.*)", body, re.S).group(1).split()
        bits = [[(int(r, 16) >> (len(r) * 4 - 1 - x)) & 1 for x in range(w)] for r in rows[:h]]
        glyphs[cp] = (dw, w, h, xo, yo, bits)
    return ascent, descent, glyphs


def pack(bits, w):
    out = []
    for row in bits:
        for b in range(0, w, 8):
            v = 0
            for x in range(8):
                if b + x < w and row[b + x]:
                    v |= 0x80 >> x
            out.append(v)
    return out


def emit(name, ascent, descent, glyphs, cps):
    table, data = [], []
    for cp in sorted(set(cps)):
        if cp not in glyphs:
            continue
        dw, w, h, xo, yo, bits = glyphs[cp]
        table.append(f"{{{cp:#x}, {w}, {h}, {xo}, {yo}, {dw}, {len(data)}}}")
        data += pack(bits, w)
    rows = [", ".join(f"{b}" for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    return (f"static const ui_glyph {name}_glyphs[] = {{\n    " + ",\n    ".join(table) + "\n};\n"
            f"static const uint8_t {name}_bits[] = {{\n    " + ",\n    ".join(rows) + "\n};\n"
            f"const ui_font ui_font_{name} = {{{name}_glyphs, {len(table)}, {name}_bits, {ascent}, {ascent + descent}}};\n"), len(table), len(data)


def main():
    a1, d1, small = parse_bdf(sys.argv[1])
    a2, d2, large = parse_bdf(sys.argv[2])
    for name, (cp, art) in ICONS.items():
        bits = [[c == "#" for c in row] for row in art]
        w, h = len(art[0]), len(art)
        # baseline-aligned like the Cozette icons: bottom 1 px below baseline
        small[cp] = (w + 1, w, h, 0, -1, bits)
    cps = TEXT + list(COZETTE_ICONS.values()) + [cp for cp, _ in ICONS.values()]
    s_src, s_n, s_b = emit("small", a1, d1, small, cps)
    l_src, l_n, l_b = emit("large", a2, d2, large, TEXT)  # icons fall back to the small font
    consts = "\n".join(f"#define ICON_{k} \"\\u{v:04X}\"" for k, v in
                       sorted({**COZETTE_ICONS, **{k: v[0] for k, v in ICONS.items()}}.items()))
    OUT.write_text("/* Generated by tools/gen_font.py - do not edit.\n"
                   " * Cozette (c) 2020 Samhain & contributors, MIT. Spleen (c) 2018-2026 Frederic Cambus, BSD-2.\n"
                   " * See FONT_LICENSES.txt. */\n#include \"ui.h\"\n\n" + s_src + "\n" + l_src)
    (OUT.parent / "include" / "ui_icons.h").write_text(
        "/* Generated by tools/gen_font.py: icon glyphs as UTF-8 string literals. */\n#pragma once\n" + consts + "\n")
    print(f"small: {s_n} glyphs {s_b} B, large: {l_n} glyphs {l_b} B")


if __name__ == "__main__":
    main()
