"""IBM Plex Sans (the Bio-Resonant UI typeface) -> components/ui/font_br.c

Anti-aliased, 4 bits per pixel (16 coverage levels: plenty on an RGB565 panel, half the flash of 8 bpp), rows padded
to whole bytes, high nibble first. Every code point the face has in the BMP (Latin incl. Extended, Greek, Cyrillic,
punctuation); anything else (icons, rare symbols) falls back to the Cozette pixel font at draw time.
A direct index for code points below 0x500 makes the common lookup O(1).

    python tools/gen_br_font.py [path/to/bio-resonant-ui]
"""
import io, sys
from pathlib import Path
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

BR = Path(sys.argv[1] if len(sys.argv) > 1 else "D:/bio-resonant-ui")
FONTS = BR / "src/styles/fonts"
OUT = Path(__file__).resolve().parent.parent / "components/ui/font_br.c"
FACES = [  # C name, Plex weight, pixel size, role
    ("small", "Regular", 12, "labels, hints, status, toasts"),
    ("title", "Medium", 12, "screen titles"),
    ("body", "Regular", 13, "list rows and values (text size: normal)"),
    ("large", "Regular", 21, "list rows and values (text size: large; the Bio-Resonant caption size)"),
]
IDX = 0x500


def load(weight, size):
    f = TTFont(FONTS / f"IBMPlexSans-{weight}.woff2")
    cps = sorted(cp for cp in f.getBestCmap() if 0x20 <= cp <= 0xFFFF and not 0xE000 <= cp <= 0xF8FF and cp not in (0xAD,))
    f.flavor = None
    buf = io.BytesIO()
    f.save(buf)
    buf.seek(0)
    return ImageFont.truetype(buf, size), cps


def emit(name, weight, size, role):
    font, cps = load(weight, size)
    asc, desc = font.getmetrics()
    bits, rows, idx = bytearray(), [], [0] * IDX
    for i, cp in enumerate(cps):
        ch = chr(cp)
        adv = round(font.getlength(ch))
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = max(0, r - l), max(0, b - t)
        off = len(bits)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
            px = img.tobytes()
            for y in range(h):
                row = [(px[y * w + x] * 15 + 127) // 255 for x in range(w)] + [0]
                bits += bytes((row[x] << 4) | row[x + 1] for x in range(0, w, 2))
        rows.append("{%d,%d,%d,%d,%d,%d,%d}" % (cp, w, h, l, -b, adv, off))
        if cp < IDX:
            idx[cp] = i + 1
    arr = ",\n".join(",".join(str(v) for v in bits[i:i + 40]) for i in range(0, len(bits), 40))
    gl = ",\n".join(", ".join(rows[i:i + 6]) for i in range(0, len(rows), 6))
    ix = ",\n".join(",".join(str(v) for v in idx[i:i + 32]) for i in range(0, IDX, 32))
    print(f"{name:6} Plex {weight} {size}px: {len(cps)} glyphs, ascent {asc}, line {asc + desc}, {len(bits)} B of bitmaps")
    return (f"/* {name}: IBM Plex Sans {weight} {size}px, {role} */\n"
            f"static const uint8_t {name}_bits[] = {{\n{arr}\n}};\n"
            f"static const ui_glyph {name}_glyphs[] = {{\n{gl}\n}};\n"
            f"static const uint16_t {name}_idx[{IDX}] = {{\n{ix}\n}};\n"
            f"const ui_font ui_font_{name} = {{{name}_glyphs, {len(cps)}, {name}_bits, {asc}, {asc + desc}, 4, {name}_idx, {IDX}}};\n\n")


out = ["/* GENERATED by tools/gen_br_font.py: do not edit. IBM Plex Sans (SIL OFL 1.1, bio-resonant-ui/src/styles/fonts),\n"
       " * 4 bits per pixel, rows padded to bytes, high nibble first. */\n", '#include "ui.h"\n\n']
out += [emit(*f) for f in FACES]
OUT.write_text("".join(out), encoding="utf-8", newline="\n")
print("wrote", OUT)
