"""CardPass logo -> components/ui/logo_data.c (a pre-baked "ROM sprite").

The same distance functions the splash used to evaluate per pixel per frame (tilted blank card, 3 px outline, key)
are evaluated once here and stored as three 4-bit coverage layers over the logo's bounding box. At runtime the
splash only looks coverage up and blends through small tables, so the theme still picks every colour.

    python tools/gen_logo.py
"""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "components/ui/logo_data.c"
W, H = 240, 135
CX, CY = 120.0, 52.0
X0, X1 = int(CX - 76), int(CX + 76)               # bounding box (the old code's own test: |dx| < 76, |dy| < 62)
Y0, Y1 = max(0, int(CY - 62)), min(H, int(CY + 62))
cs, sn = math.cos(math.radians(-18)), math.sin(math.radians(-18))
kc, ks = math.cos(math.radians(-38)), math.sin(math.radians(-38))


def clamp01(v):
    return 0.0 if v < 0 else 1.0 if v > 1 else v


def sd_box(x, y, hw, hh, r):
    qx, qy = abs(x) - (hw - r), abs(y) - (hh - r)
    ox, oy = max(qx, 0.0), max(qy, 0.0)
    return math.hypot(ox, oy) + min(max(qx, qy), 0.0) - r


def coverage(x, y):
    dx, dy = x + 0.5 - CX, y + 0.5 - CY
    if not (abs(dx) < 76 and abs(dy) < 62):
        return 0.0, 0.0, 0.0
    u, v = dx * cs + dy * sn, -dx * sn + dy * cs
    sc = sd_box(u, v, 52, 33, 9)
    card = clamp01(0.5 - sc)
    line = clamp01(0.5 - (abs(sc + 1.5) - 1.5))
    ku, kv = u * kc + v * ks, -u * ks + v * kc
    bl = math.hypot(ku - 17, kv)
    ring = max(bl - 9, 4 - bl)
    shaft = sd_box(ku + 8, kv, 18, 2.4, 0)
    t1, t2 = sd_box(ku + 18, kv + 5, 1.8, 5, 0), sd_box(ku + 10, kv + 4, 1.8, 4, 0)
    key = clamp01(0.5 - min(ring, shaft, t1, t2))
    return card, line, key


q = lambda v: int(v * 15 + 0.5)
layers = [bytearray(), bytearray(), bytearray()]
for y in range(Y0, Y1):
    vals = [coverage(x, y) for x in range(X0, X1)] + [(0.0, 0.0, 0.0)]
    for li in range(3):
        layers[li] += bytes((q(vals[x][li]) << 4) | q(vals[x + 1][li]) for x in range(0, X1 - X0, 2))
fmt = lambda b: ",\n".join(",".join(str(v) for v in b[i:i + 38]) for i in range(0, len(b), 38))
src = f"""/* GENERATED by tools/gen_logo.py: do not edit. The CardPass logo as three 4-bit coverage layers (card, outline,
 * key) over its bounding box, rows padded to bytes, high nibble first. */
#include <stdint.h>
const int logo_x0 = {X0}, logo_y0 = {Y0}, logo_w = {X1 - X0}, logo_h = {Y1 - Y0};
const uint8_t logo_card[] = {{\n{fmt(layers[0])}\n}};
const uint8_t logo_line[] = {{\n{fmt(layers[1])}\n}};
const uint8_t logo_key[] = {{\n{fmt(layers[2])}\n}};
"""
OUT.write_text(src, encoding="utf-8", newline="\n")
print(f"logo {X1 - X0}x{Y1 - Y0} at ({X0},{Y0}), {sum(len(l) for l in layers)} B in flash")
