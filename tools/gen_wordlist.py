"""EFF large wordlist -> components/gen/wordlist.c (front-coded, ~half size).

Each word: one byte (shared prefix length with previous word + 1, always < 0x20)
followed by the remaining characters.

    curl -O https://www.eff.org/files/2016/07/18/eff_large_wordlist.txt
    python tools/gen_wordlist.py eff_large_wordlist.txt
"""
import hashlib, sys
from pathlib import Path

SHA256 = "addd35536511597a02fa0a9ff1e5284677b8883b83e986e43f15a3db996b903e"
raw = Path(sys.argv[1]).read_bytes()
assert hashlib.sha256(raw).hexdigest() == SHA256, "unexpected wordlist file"
words = [l.split()[1] for l in raw.decode().splitlines() if l.strip()]
assert len(words) == 7776

out, prev = bytearray(), ""
for w in words:
    p = 0
    while p < min(len(w), len(prev), 30) and w[p] == prev[p]:
        p += 1
    out += bytes([p + 1]) + w[p:].encode()
    prev = w

lines = [",".join(str(b) for b in out[i:i + 32]) for i in range(0, len(out), 32)]
dst = Path(__file__).resolve().parent.parent / "components/gen/wordlist.c"
dst.write_text(
    "/* Generated by tools/gen_wordlist.py. EFF Large Wordlist for Passphrases,\n"
    " * (c) Electronic Frontier Foundation, CC BY 3.0 US, https://www.eff.org/dice */\n"
    "#include <stdint.h>\n\n"
    f"const unsigned gen_wordlist_count = {len(words)};\n"
    f"const unsigned gen_wordlist_size = {len(out)};\n"
    "const uint8_t gen_wordlist[] = {\n" + ",\n".join(lines) + "\n};\n")
print(f"{len(raw)} -> {len(out)} bytes")
