"""Letter-pair index of the EFF word list -> components/strength/wordpairs.c (ROM: no RAM, no start-up pass).

The list (components/gen/wordlist.c) is sorted and front-coded, so the words starting with each two-letter pair are
contiguous, and where a pair starts a word shares at most its first letter with the previous one. For each pair:
byte offset of its first word and how many words it has. Words not starting with two letters are listed in full.

    python tools/gen_wordpairs.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = (ROOT / "components/gen/wordlist.c").read_text(encoding="utf-8")
data = [int(v) for v in re.search(r"gen_wordlist\[\]\s*=\s*\{(.*?)\};", src, re.S).group(1).replace("\n", "").split(",") if v.strip()]

pos_tab, len_tab, odd = [0] * 676, [0] * 676, []
word, i, last = "", 0, -1
while i < len(data):
    start = i
    keep = data[i] - 1
    i += 1
    rest = []
    while i < len(data) and data[i] >= 0x20:
        rest.append(chr(data[i]))
        i += 1
    word = word[:keep] + "".join(rest)
    a, b = (ord(word[0]) - 97, ord(word[1]) - 97) if len(word) >= 2 else (-1, -1)
    if not (0 <= a < 26 and 0 <= b < 26):
        odd.append(word)
        last = -1
        continue
    k = a * 26 + b
    if k != last:
        assert keep <= 1, (word, keep)          # the property gen_words_at() relies on
        pos_tab[k] = start
    len_tab[k] += 1
    last = k
assert len(odd) <= 8, odd
fmt = lambda v: ",\n".join(",".join(str(x) for x in v[j:j + 26]) for j in range(0, len(v), 26))
out = f"""/* GENERATED by tools/gen_wordpairs.py from components/gen/wordlist.c: do not edit.
 * For each first-letter pair (a*26+b): byte offset of its first word in gen_wordlist[] and its word count. */
#include <stdint.h>

const uint16_t strength_pair_pos[676] = {{\n{fmt(pos_tab)}\n}};
const uint16_t strength_pair_len[676] = {{\n{fmt(len_tab)}\n}};
const char strength_odd_words[][16] = {{{", ".join('"' + w + '"' for w in odd)}}};
const int strength_n_odd = {len(odd)};
"""
(ROOT / "components/strength/wordpairs.c").write_text(out, encoding="utf-8", newline="\n")
print(f"{sum(1 for x in len_tab if x)} pairs, {len(odd)} odd words: {odd}")
