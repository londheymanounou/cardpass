"""Bio-Resonant UI themes -> components/ui/theme_br.c

Reads the four circadian modes (Dusk, Deep night, Daylight, Sunrise) from the Bio-Resonant token build
(src/styles/tokens.css: a mode block overrides its polarity's [data-theme] block) and maps the semantic roles onto
CardPass's theme struct. Colours are quantised to RGB565, then APCA contrast is re-checked on the quantised values,
like bio-resonant-ui/cardputer/gen-tokens.mjs does: quantisation must not break a floor.

    python tools/gen_br_theme.py [path/to/bio-resonant-ui]
"""
import re, sys
from pathlib import Path

BR = Path(sys.argv[1] if len(sys.argv) > 1 else "D:/bio-resonant-ui")
OUT = Path(__file__).resolve().parent.parent / "components" / "ui" / "theme_br.c"
css = (BR / "src/styles/tokens.css").read_text(encoding="utf-8")


def block(selector):
    """First top-level block for this selector (the later @media copies are the P3 variants)."""
    m = re.search(re.escape(selector) + r"\s*\{(.*?)\n\}", css, re.S)
    if not m:
        raise SystemExit(f"no block {selector}")
    return dict(re.findall(r"--br-([a-z0-9-]+):\s*(#[0-9a-fA-F]{6})\s*;", m.group(1)))


light, dark = block(':root[data-theme="light"]'), block(':root[data-theme="dark"]')
MODES = [("Dusk", "dusk", dark), ("Deep night", "deep-night", dark), ("Daylight", "daylight", light), ("Sunrise", "sunrise", light)]
FLOOR = {"dusk": 90, "deep-night": 75, "daylight": 90, "sunrise": 90}   # SPECIFICATION 3.10: body floor per mode


def rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


def to565(h):
    r, g, b = rgb(h)
    return ((r * 31 + 127) // 255) << 11 | ((g * 63 + 127) // 255) << 5 | ((b * 31 + 127) // 255)


def from565(c):
    return (((c >> 11) & 31) * 255 // 31, ((c >> 5) & 63) * 255 // 63, (c & 31) * 255 // 31)


def apca(txt, bg):
    """APCA-W3 0.0.98G Lc of txt on bg (sRGB 0..255 tuples)."""
    def y(c):
        r, g, b = ((v / 255) ** 2.4 for v in c)
        Y = 0.2126729 * r + 0.7151522 * g + 0.0721750 * b
        return Y + (0.022 - Y) ** 1.414 if Y < 0.022 else Y
    yt, yb = y(txt), y(bg)
    if abs(yb - yt) < 0.0005:
        return 0.0
    if yb > yt:
        s = (yb ** 0.56 - yt ** 0.57) * 1.14
        return 0.0 if s < 0.1 else (s - 0.027) * 100
    s = (yb ** 0.65 - yt ** 0.62) * 1.14
    return 0.0 if s > -0.1 else (s + 0.027) * 100


ROLES = {   # CardPass role -> Bio-Resonant token
    "bg": "surface-base", "fg": "ink-primary", "dim": "ink-secondary", "faint": "ink-tertiary",
    "accent": "accent-primary", "sel_bg": "accent-fill-primary", "sel_fg": "ink-on-accent",
    "bar_bg": "surface-base", "bar_fg": "ink-primary", "ok": "accent-primary", "warn": "accent-caution",
    "danger": "accent-text-critical", "field_bg": "surface-sunken", "raised": "surface-raised",
    "overlay": "surface-overlay", "rule": "border-strong", "ring": "accent-primary", "focus": "border-focus",
}

out = ["/* GENERATED by tools/gen_br_theme.py from bio-resonant-ui/src/styles/tokens.css: do not edit.",
       " * The four Bio-Resonant circadian modes (SPECIFICATION 3.10), quantised to RGB565. */",
       '#include "ui.h"', "", "const ui_theme ui_themes[UI_THEMES] = {"]
report = []
for name, mode, base in MODES:
    t = dict(base)
    t.update(block(f':root[data-mode="{mode}"]'))
    t.setdefault("accent-text-critical", t["accent-critical"])
    c = {role: to565(t[tok]) for role, tok in ROLES.items()}
    # Contrast-preserving quantisation: each ink takes, of its 27 nearest RGB565 neighbours, the one whose APCA
    # contrast on its surface is closest to the exact value (colour error breaks ties). Surfaces round normally.
    for role, on in (("fg", "bg"), ("dim", "bg"), ("faint", "bg"), ("accent", "bg"), ("warn", "bg"), ("danger", "bg"),
                     ("sel_fg", "sel_bg"), ("bar_fg", "bar_bg")):
        want = abs(apca(rgb(t[ROLES[role]]), rgb(t[ROLES[on]])))
        r0, g0, b0 = (c[role] >> 11) & 31, (c[role] >> 5) & 63, c[role] & 31
        exact = rgb(t[ROLES[role]])
        best = None
        for dr in (-1, 0, 1):
            for dg in (-1, 0, 1):
                for db in (-1, 0, 1):
                    r, g, b = r0 + dr, g0 + dg, b0 + db
                    if not (0 <= r <= 31 and 0 <= g <= 63 and 0 <= b <= 31):
                        continue
                    cand = r << 11 | g << 5 | b
                    err = sum((x - y) ** 2 for x, y in zip(from565(cand), exact))
                    key = (abs(abs(apca(from565(cand), from565(c[on]))) - want), err)
                    if best is None or key < best[0]:
                        best = (key, cand)
        c[role] = best[1]
    fields = ", ".join(f".{k} = 0x{v:04x}" for k, v in c.items())
    out.append(f"    {{{fields}, .dark = {'true' if base is dark else 'false'}}},   /* {name} */")
    # floors on the body surfaces (BR's verifier); on every pair, RGB565 may not cost more than 1.5 Lc
    for fg, bg, floor in (("fg", "bg", FLOOR[mode]), ("fg", "raised", FLOOR[mode]), ("fg", "field_bg", None),
                          ("sel_fg", "sel_bg", None), ("dim", "bg", None), ("faint", "bg", None), ("accent", "bg", None)):
        exact = abs(apca(rgb(t[ROLES[fg]]), rgb(t[ROLES[bg]])))
        lc = abs(apca(from565(c[fg]), from565(c[bg])))
        report.append(f"{name:10} {fg:6} on {bg:8} Lc {lc:5.1f} (exact {exact:5.1f}{f', floor {floor}' if floor else ''})")
        if floor and lc + 1.0 < floor:
            raise SystemExit(f"below the floor: {name} {fg} on {bg} Lc {lc:.1f} < {floor}")
        if lc < exact - 1.5:
            raise SystemExit(f"RGB565 broke contrast: {name} {fg} on {bg} Lc {lc:.1f} vs exact {exact:.1f}")
out += ["};", "", 'const char *const ui_theme_names[UI_THEMES] = {' + ", ".join(f'"{n}"' for n, _, _ in MODES) + "};", ""]
OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
print("\n".join(report))
print("wrote", OUT)
