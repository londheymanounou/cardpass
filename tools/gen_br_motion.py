"""Bio-Resonant motion -> components/ui/motion_br.h

The design system defines motion as a spring (element tier: omega 24.39 rad/s, zeta 0.82) and ships its step
response as the CSS easing `motion.easing` = linear(v0, v1 p1%, ...). This samples that curve at 25 evenly spaced
times into a Q8 table (0..256) and takes the duration tiers (feedback / element / view) from the same token build,
so the animations follow the tokens instead of a hand-picked ease-out quad.

    python tools/gen_br_motion.py [path/to/bio-resonant-ui]
"""
import json, re, sys
from pathlib import Path

BR = Path(sys.argv[1] if len(sys.argv) > 1 else "D:/bio-resonant-ui")
OUT = Path(__file__).resolve().parent.parent / "components/ui/motion_br.h"
tok = json.load(open(BR / "dist/tokens.json", encoding="utf-8"))
val = lambda k: tok[k]["value"]

stops = []                                             # (position 0..1, value)
items = re.match(r"linear\((.*)\)", val("motion.easing")).group(1).split(",")
for i, it in enumerate(items):
    parts = it.split()
    v = float(parts[0])
    p = float(parts[1].rstrip("%")) / 100 if len(parts) > 1 else (0.0 if i == 0 else 1.0 if i == len(items) - 1 else None)
    stops.append([p, v])
for i, s in enumerate(stops):                          # CSS rule: missing positions are spread evenly between known ones
    if s[0] is None:
        j = next(k for k in range(i, len(stops)) if stops[k][0] is not None)
        a = stops[i - 1][0]
        s[0] = a + (stops[j][0] - a) / (j - i + 1)


def at(t):
    for (p0, v0), (p1, v1) in zip(stops, stops[1:]):
        if t <= p1:
            return v0 if p1 == p0 else v0 + (v1 - v0) * (t - p0) / (p1 - p0)
    return stops[-1][1]


N = 25
table = [round(at(i / (N - 1)) * 256) for i in range(N)]
table[-1] = 256
ms = lambda k: int(round(float(str(val(k)).rstrip("ms"))))
out = f"""/* GENERATED by tools/gen_br_motion.py from bio-resonant-ui dist/tokens.json: do not edit.
 * The element-tier spring step response (omega {val('motion.element-omega')}, zeta {val('motion.damping')}), sampled at {N} evenly spaced
 * times, Q8; and the duration tiers. */
#pragma once
#include <stdint.h>

#define BR_MS_FEEDBACK {ms('motion.feedback-duration')}
#define BR_MS_ELEMENT {ms('motion.element-duration')}
#define BR_MS_VIEW {ms('motion.view-duration')}
static const uint16_t BR_EASE[{N}] = {{{", ".join(map(str, table))}}};

/* t: 0..256 of the duration -> 0..256 (linear between the samples) */
static inline int br_ease(int t)
{{
    if (t <= 0) return 0;
    if (t >= 256) return 256;
    int i = t * {N - 1} >> 8, f = (t * {N - 1}) & 255;
    return BR_EASE[i] + ((BR_EASE[i + 1] - BR_EASE[i]) * f >> 8);
}}
"""
OUT.write_text(out, encoding="utf-8", newline="\n")
print("ease", table, "\nfeedback/element/view ms", ms("motion.feedback-duration"), ms("motion.element-duration"), ms("motion.view-duration"))
